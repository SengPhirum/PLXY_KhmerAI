#!/usr/bin/env python3
"""Turn benchmark rows into a production configuration recommendation (Phase 13).

    python load_test/analyze_results.py --input reports/ollama_benchmark/summary-*.jsonl

Applies the §Phase 13 decision rule: do NOT force 10 active generation streams if
latency becomes unacceptable.  A configuration is *acceptable* when it meets the
SLOs in ``configs/base.yaml``; among acceptable configurations the one with the
highest sustained throughput at the target client count wins.
"""

from __future__ import annotations

import argparse
import glob
import json
import sys
from pathlib import Path
from typing import Any

_REPO_ROOT = Path(__file__).resolve().parent.parent
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from common.config import load_config  # noqa: E402
from common.io import atomic_write_text, read_jsonl  # noqa: E402


def load_rows(patterns: list[str]) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for pattern in patterns:
        for path in sorted(glob.glob(pattern)):
            rows.extend(read_jsonl(path, skip_invalid=True))
    return rows


def evaluate(rows: list[dict[str, Any]], slo: dict[str, Any], target_clients: int) -> dict[str, Any]:
    latency = (slo.get("latency") or {})
    availability = (slo.get("availability") or {})
    ttft_limit_ms = float(latency.get("time_to_first_token_p95_seconds", 2.5)) * 1000
    p95_limit_ms = float(latency.get("end_to_end_p95_seconds", 12.0)) * 1000
    success_floor = float(availability.get("api_success_rate", 0.995))

    at_target = [r for r in rows if int(r.get("clients", 0)) == target_clients]
    scored: list[dict[str, Any]] = []
    for row in at_target:
        ttft = row.get("ttft_p95_ms") or 0.0
        p95 = row.get("latency_p95_ms") or 0.0
        success = float(row.get("success_rate", 0.0))
        violations = []
        if ttft > ttft_limit_ms:
            violations.append(f"ttft_p95 {ttft:.0f}ms > {ttft_limit_ms:.0f}ms")
        if p95 > p95_limit_ms:
            violations.append(f"latency_p95 {p95:.0f}ms > {p95_limit_ms:.0f}ms")
        if success < success_floor:
            violations.append(f"success {success:.3f} < {success_floor}")
        if row.get("failures"):
            violations.append(f"{row['failures']} failed request(s)")
        scored.append({**row, "violations": violations, "acceptable": not violations})

    acceptable = [r for r in scored if r["acceptable"]]
    winner = (
        max(acceptable, key=lambda r: (r.get("requests_per_second", 0.0), -(r.get("latency_p95_ms") or 0)))
        if acceptable
        else None
    )
    return {
        "target_clients": target_clients,
        "configurations_tested": len(rows),
        "at_target_clients": len(at_target),
        "acceptable": len(acceptable),
        "slo": {
            "ttft_p95_ms": ttft_limit_ms,
            "latency_p95_ms": p95_limit_ms,
            "success_rate": success_floor,
        },
        "recommended": winner,
        "rejected": [
            {k: r.get(k) for k in ("model", "ollama_num_parallel", "context", "violations")}
            for r in scored
            if not r["acceptable"]
        ],
    }


def to_markdown(analysis: dict[str, Any], rows: list[dict[str, Any]]) -> str:
    lines = [
        "# Ollama tuning - measured results",
        "",
        "<!-- GENERATED by load_test/analyze_results.py. Every value below was measured. -->",
        "",
        f"Configurations tested: {analysis['configurations_tested']}  ",
        f"Target connected clients: {analysis['target_clients']}  ",
        f"Acceptable configurations at target: {analysis['acceptable']}",
        "",
        "## SLO thresholds applied",
        "",
        "| Metric | Threshold |",
        "|---|---:|",
        f"| TTFT p95 | {analysis['slo']['ttft_p95_ms']:.0f} ms |",
        f"| End-to-end p95 | {analysis['slo']['latency_p95_ms']:.0f} ms |",
        f"| Success rate | {analysis['slo']['success_rate']:.3f} |",
        "",
        "## Full matrix",
        "",
        "| Model | NUM_PARALLEL | Context | Clients | TTFT p95 | p50 | p95 | p99 | tok/s | ok |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for row in sorted(
        rows, key=lambda r: (str(r.get("model")), r.get("context", 0), r.get("ollama_num_parallel", 0), r.get("clients", 0))
    ):
        lines.append(
            f"| {row.get('model')} | {row.get('ollama_num_parallel')} | {row.get('context')} | "
            f"{row.get('clients')} | {row.get('ttft_p95_ms')} | {row.get('latency_p50_ms')} | "
            f"{row.get('latency_p95_ms')} | {row.get('latency_p99_ms')} | "
            f"{row.get('tokens_per_second')} | {row.get('success_rate')} |"
        )

    winner = analysis.get("recommended")
    lines += ["", "## Recommendation", ""]
    if winner:
        lines += [
            f"**Model**: `{winner.get('model')}`  ",
            f"**OLLAMA_NUM_PARALLEL**: {winner.get('ollama_num_parallel')}  ",
            f"**OLLAMA_CONTEXT_LENGTH**: {winner.get('context')}  ",
            "",
            f"Measured at {analysis['target_clients']} connected clients: "
            f"TTFT p95 {winner.get('ttft_p95_ms')} ms, end-to-end p95 "
            f"{winner.get('latency_p95_ms')} ms, {winner.get('tokens_per_second')} tokens/s, "
            f"success {winner.get('success_rate')}.",
            "",
            "Apply to `configs/production/ollama_9b.yaml` and `.env`, then set the API's",
            "`KHMERAI_MAX_ACTIVE_GENERATIONS` to at most this `OLLAMA_NUM_PARALLEL`.",
        ]
    else:
        lines += [
            "**No configuration met the SLOs at the target client count.**",
            "",
            "Per §Phase 13 this is an expected outcome, not a failure: it is acceptable to",
            "serve 10+ *connected* clients with 4-6 *active* generations plus a queue when",
            "that produces a better measured customer experience. Options, in order:",
            "",
            "1. Reduce `OLLAMA_NUM_PARALLEL` and let the API queue (raise `max_queue_depth`).",
            "2. Reduce `OLLAMA_CONTEXT_LENGTH` to 4096 - it multiplies KV-cache memory.",
            "3. Switch to the 4B model for the high-concurrency tier.",
            "4. Reduce `num_predict`; long answers dominate tail latency.",
            "",
            "Rejected configurations and why:",
            "",
        ]
        for rejected in analysis["rejected"][:20]:
            lines.append(
                f"- `{rejected.get('model')}` parallel={rejected.get('ollama_num_parallel')} "
                f"context={rejected.get('context')}: {'; '.join(rejected.get('violations') or [])}"
            )
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python load_test/analyze_results.py")
    parser.add_argument("--input", nargs="+", required=True, help="summary JSONL file(s) or globs")
    parser.add_argument("--output", default="reports/ollama_tuning.md")
    parser.add_argument("--target-clients", type=int, default=10)
    parser.add_argument("--config", default="configs/base.yaml")
    args = parser.parse_args(argv)

    rows = load_rows(args.input)
    if not rows:
        print(f"no rows found in {args.input}", file=sys.stderr)
        return 1

    slo = load_config(args.config).get("slo", {}) or {}
    analysis = evaluate(rows, slo, args.target_clients)
    markdown = to_markdown(analysis, rows)
    atomic_write_text(_REPO_ROOT / args.output, markdown)

    print(json.dumps({k: v for k, v in analysis.items() if k != "rejected"}, indent=2))
    print(f"\nwritten: {args.output}")
    return 0 if analysis.get("recommended") else 2


if __name__ == "__main__":
    sys.exit(main())
